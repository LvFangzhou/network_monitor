router = APIRouter()

TACACS_DATA_DIR = Path("/app/data/tacacs")
TACACS_CONFIG_FILE = TACACS_DATA_DIR / "tac_plus.cfg"
TACACS_LOG_FILE = TACACS_DATA_DIR / "logs" / "tacacs.log"
TACACS_SETTINGS_FILE = TACACS_DATA_DIR / "settings.json"
TACACS_CONTAINER_NAME = "nm-tacacs"
DOCKER_SOCKET = "/var/run/docker.sock"

LOG_PATTERN = re.compile(r"(\w+\s+\d+\s+\d+:\d+:\d+)\s+(\d+\.\d+\.\d+\.\d+)\s+(\w+)\s+(\S+)\s+(\S+).*?cmd=(.*)")
MONTH_MAP = {
    "Jan": 1, "Feb": 2, "Mar": 3, "Apr": 4, "May": 5, "Jun": 6,
    "Jul": 7, "Aug": 8, "Sep": 9, "Oct": 10, "Nov": 11, "Dec": 12,
}


def _ensure_data_dir() -> None:
    (TACACS_DATA_DIR / "logs").mkdir(parents=True, exist_ok=True)


def _ensure_config_file(settings_payload: Optional[Dict[str, Any]] = None) -> None:
    _ensure_data_dir()
    if TACACS_CONFIG_FILE.exists() and TACACS_CONFIG_FILE.is_dir():
        TACACS_CONFIG_FILE.rmdir()
    if not TACACS_CONFIG_FILE.exists():
        TACACS_CONFIG_FILE.write_text(_render_config(settings_payload or _load_settings()), encoding="utf-8")


def _detect_notification_type(webhook_url: str) -> str:
    url = (webhook_url or "").strip().lower()
    if "work.weixin.qq.com" in url or "qyapi.weixin.qq.com" in url:
        return "wechat"
    if "oapi.dingtalk.com" in url or "api.dingtalk.com" in url:
        return "dingtalk"
    if "open.feishu.cn" in url or "open.larksuite.com" in url:
        return "feishu"
    return "webhook"


def _parse_log_time(raw_time: str) -> Optional[str]:
    try:
        month_text, day, time_text = raw_time.split()
        hour, minute, second = [int(item) for item in time_text.split(":")]
        parsed = datetime(datetime.now().year, MONTH_MAP[month_text], int(day), hour, minute, second)
        return (parsed + timedelta(hours=8)).strftime("%Y-%m-%d %H:%M:%S")
    except Exception:
        return None


def _extract_command(raw_command: str) -> str:
    text = (raw_command or "").strip()
    if not text:
        return ""
    marker_match = re.search(r"\s+(cmd-arg|err_msg|start_time)=", text)
    command = text[:marker_match.start()].strip() if marker_match else text
    rest = text[marker_match.start():] if marker_match else ""
    arg_match = re.search(
        r"\bcmd-arg=(.*?)(?=\s+(?:err_msg|start_time)=|$)",
        rest,
    )
    cmd_arg = arg_match.group(1).strip() if arg_match else ""
    if cmd_arg:
        return f"{command} {cmd_arg}".strip()
    return command


def _render_command_block(command: Dict[str, Any]) -> str:
    name = str(command.get("name") or "").strip()
    if not name:
        return ""
    permits = command.get("permit") or []
    denies = command.get("deny") or []
    lines = [f"    cmd = {name} {{"]
    for pattern in permits:
        lines.append(f"        permit {pattern}")
    for pattern in denies:
        lines.append(f"        deny {pattern}")
    lines.append("    }")
    return "\n".join(lines)


def _render_config(payload: Dict[str, Any]) -> str:
    key = str(payload.get("key") or "testing123").replace('"', '\\"')
    accounting_file = str(payload.get("accounting_file") or "/var/log/tacacs+/tacacs.log")
    roles = payload.get("roles") or []
    users = payload.get("users") or []

    lines = [
        "# Generated by 并行网络运营平台",
        f'key = "{key}"',
        "",
        f"accounting file = {accounting_file}",
        "",
    ]

    for role in roles:
        name = str(role.get("name") or "").strip()
        if not name:
            continue
        priv_lvl = int(role.get("priv_lvl") or 1)
        default_service = "permit" if role.get("default_permit", True) else "deny"
        lines.extend([
            f"group = {name} {{",
            f"    default service = {default_service}",
            "    service = exec {",
            f"        priv-lvl = {priv_lvl}",
            "    }",
            "    service = shell {",
            f"        priv-lvl = {priv_lvl}",
            "    }",
        ])
        for command in role.get("commands") or []:
            block = _render_command_block(command)
            if block:
                lines.append(block)
        lines.extend(["}", ""])

    for account in users:
        username = str(account.get("username") or "").strip()
        password = str(account.get("password") or "").replace('"', '\\"')
        role = str(account.get("role") or "").strip()
        if not username or not password or not role:
            continue
        lines.extend([
            f"user = {username} {{",
            f'    login = cleartext "{password}"',
            f'    pap = cleartext "{password}"',
            f"    member = {role}",
            "}",
            "",
        ])

    return "\n".join(lines).rstrip() + "\n"


