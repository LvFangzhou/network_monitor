@router.get("/logs", response_model=dict)
async def list_tacacs_logs(
    current_user: User = Depends(get_current_active_user),
    skip: int = Query(0, ge=0),
    limit: int = Query(200, ge=1, le=1000),
    search: Optional[str] = None,
    start_time: Optional[str] = None,
    end_time: Optional[str] = None,
    device_ip: Optional[str] = None,
    username: Optional[str] = None,
    command: Optional[str] = None,
):
    _ensure_data_dir()
    if not TACACS_LOG_FILE.exists():
        return {"total": 0, "items": [], "path": str(TACACS_LOG_FILE)}

    keyword = (search or "").strip().lower()
    start_value = (start_time or "").strip()
    end_value = (end_time or "").strip()
    device_value = (device_ip or "").strip().lower()
    username_value = (username or "").strip().lower()
    command_value = (command or "").strip().lower()
    total = 0
    items: List[Dict[str, Any]] = []
    for line in reversed(TACACS_LOG_FILE.read_text(encoding="utf-8", errors="ignore").splitlines()):
        if "cmd=" not in line:
            continue
        match = LOG_PATTERN.search(line)
        if not match:
            continue
        command_text = _extract_command(match.group(6))
        if not command_text or command_text in {"startup"}:
            continue
        item = {
            "time": _parse_log_time(match.group(1)) or match.group(1),
            "device_ip": match.group(2),
            "username": match.group(3),
            "tty": match.group(4),
            "client_ip": match.group(5),
            "command": command_text,
            "raw": line,
        }
        item_time = str(item["time"])
        if start_value and item_time < start_value:
            continue
        if end_value and item_time > end_value:
            continue
        if device_value and device_value not in item["device_ip"].lower():
            continue
        if username_value and username_value not in item["username"].lower():
            continue
        if command_value and command_value not in item["command"].lower():
            continue
        if keyword and keyword not in " ".join(str(value).lower() for value in item.values()):
            continue
        total += 1
        if total <= skip:
            continue
        if len(items) < limit:
            items.append(item)
    return {"total": total, "items": items, "path": str(TACACS_LOG_FILE)}
